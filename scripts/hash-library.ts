// Writes api/_lib/libraryHashes.ts: the look-alike fingerprint of every photo
// in Scout's library (site/img/library), so the server can tell when a player
// hands in one of Scout's own photos as their sighting.
//
//   npx tsx scripts/hash-library.ts
//
// Run it after adding or replacing a library photo. A unit test
// (tests/phash.test.ts) fails if the file is out of date.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { photoFingerprint } from '../api/_lib/phash';

export function libraryHashes(): Record<string, string> {
  const dir = join(__dirname, '..', 'site', 'img', 'library');
  const out: Record<string, string> = {};
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.jpg')).sort()) {
    const { phash } = photoFingerprint(readFileSync(join(dir, file)).toString('base64'));
    if (phash) out[file.replace(/\.jpg$/, '')] = phash;
  }
  return out;
}

if (require.main === module) {
  const hashes = libraryHashes();
  const lines = Object.entries(hashes).map(([slug, h]) => `  ${JSON.stringify(slug)}: '${h}',`);
  writeFileSync(
    join(__dirname, '..', 'api', '_lib', 'libraryHashes.ts'),
    `// Generated by scripts/hash-library.ts — do not edit by hand.\n// The look-alike fingerprint (api/_lib/phash.ts) of each photo in Scout's library.\nexport const LIBRARY_HASHES: Record<string, string> = {\n${lines.join('\n')}\n};\n`,
  );
  console.log(`wrote ${lines.length} fingerprints`);
}
