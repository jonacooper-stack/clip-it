// The blocked-language check exists twice: in the app and server code
// (shared/moderation.ts) and in the database (a trigger, so the rule holds
// even for someone who talks to the database directly). This script writes
// the database version from the shared one, so there is still one word list.
//
//   npx tsx scripts/gen-moderation-sql.ts            prints the SQL to paste into a new migration
//   npx tsx scripts/gen-moderation-sql.ts --write    also rewrites supabase/tests/moderation.test.sql
//
// After changing the list in shared/moderation.ts: add a new migration that
// contains the printed SQL, and run with --write. Unit tests fail until the
// newest migration and the test file match the shared list.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { BLOCKED_TERMS, LEET, hasBlockedLanguage } from '../shared/moderation';

export const SQL_START = '-- >>> generated by scripts/gen-moderation-sql.ts from shared/moderation.ts: do not edit by hand >>>';
export const SQL_END = '-- <<< generated <<<';

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function moderationSql(): string {
  const from = Object.keys(LEET).join('');
  const to = Object.values(LEET).join('');
  const terms = BLOCKED_TERMS.map(lit).join(', ');
  const long = BLOCKED_TERMS.filter((t) => t.length >= 4).map(lit).join(', ');
  return `${SQL_START}
-- One word, the way the filter sees it: lower case, look-alike digits and
-- symbols turned back into letters, everything but a–z dropped, and a letter
-- repeated three or more times cut to two ("fuuuuck" -> "fuuck").
create or replace function private.squash_word(w text)
returns text
language sql
immutable
as $$
  select regexp_replace(
    regexp_replace(translate(lower(w), ${lit(from)}, ${lit(to)}), '[^a-z]', '', 'g'),
    '(.)\\1{2,}', '\\1\\1', 'g');
$$;

-- True if the text contains language that isn't allowed on ClipIt. The same
-- rule as hasBlockedLanguage in shared/moderation.ts: any single word on the
-- list (also with doubled letters collapsed), or the whole text spelling a
-- listed word of four or more letters once spaces and punctuation are removed
-- ("f u c k"). Look-alike characters are folded first (normalize NFKC), so
-- this is never more lenient than the app.
create or replace function private.has_blocked_language(t text)
returns boolean
language sql
immutable
as $$
  with input as (
    select normalize(coalesce(t, ''), NFKC) as s
  ), words as (
    select private.squash_word(tok) as n
    from input,
      regexp_split_to_table(
        regexp_replace(input.s, '[[:space:]\\u00a0\\u1680\\u2000-\\u200a\\u2028\\u2029\\u202f\\u205f\\u3000\\ufeff]+', ' ', 'g'),
        ' ') as tok
  )
  select exists (
      select 1 from words
      where n <> ''
        and (n = any (array[${terms}])
          or regexp_replace(n, '(.)\\1+', '\\1', 'g') = any (array[${terms}]))
    )
    or private.squash_word((select s from input)) = any (array[${long}]);
$$;
${SQL_END}`;
}

