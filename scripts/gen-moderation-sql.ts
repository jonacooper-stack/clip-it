export function moderationTestSql(): string {
  const rows = SAMPLES.map((s) => `  (${lit(s)}, ${hasBlockedLanguage(s)})`).join(',\n');
  return `-- Generated by scripts/gen-moderation-sql.ts (--write): do not edit by hand.
-- Each sample with the answer shared/moderation.ts gives. The database must
-- block everything the app blocks (it may block a little more: it also folds
-- look-alike characters).
do $samples$
declare
  r record;
  bad int := 0;
begin
  for r in
    select * from (values
${rows}
    ) as v(sample, app_blocks)
  loop
    if r.app_blocks and not private.has_blocked_language(r.sample) then
      bad := bad + 1;
      raise notice 'FAIL the database allows what the app blocks: %', r.sample;
    elsif not r.app_blocks and private.has_blocked_language(r.sample) then
      bad := bad + 1;
      raise notice 'FAIL the database blocks what the app allows: %', r.sample;
    end if;
  end loop;
  if bad = 0 then raise notice 'PASS blocked-language filter agrees with the app on ${SAMPLES.length} samples'; end if;
end $samples$;
`;
}

